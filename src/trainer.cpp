// ChessBot trainer / data generator.
//
// Usage:
//   trainer datagen <games> <depth> <out.txt> [seed]
//   trainer train <data.txt> <epochs> <out_nnue.cpp>
//
// The data file stores one position per line as "<FEN>|<score>", where score
// is the search score from the side to move. The trainer fits a small
// HalfKP-like network (768 -> 32 -> 1) to the residual
// (search score - classical evaluation), which is then blended into the
// evaluation by the engine.
#include "engine.hpp"

#include <array>
#include <cmath>
#include <fstream>
#include <iomanip>
#include <numeric>
#include <random>
#include <vector>

namespace {

using namespace chess;

struct Sample {
    std::array<uint16_t, 64> feat;
    uint8_t n = 0;
    float target = 0.0f;
    float baseline = 0.0f;
};

std::vector<Sample> loadSamples(const std::string& path, bool direct) {
    std::ifstream in(path);
    std::vector<Sample> samples;
    std::string line;
    int skipped = 0;
    while (std::getline(in, line)) {
        if (line.empty()) continue;
        size_t sep = line.rfind('|');
        if (sep == std::string::npos) { ++skipped; continue; }
        std::string fen = line.substr(0, sep);
        int score = 0;
        try {
            score = std::stoi(line.substr(sep + 1));
        } catch (...) { ++skipped; continue; }
        if (score >= MATE_IN_MAX || score <= -MATE_IN_MAX) continue;

        Position pos;
        if (!pos.setFen(fen)) { ++skipped; continue; }
        int base = classicalEvaluate(pos);
        Sample s;
        int features[64];
        int n = NNUE::featureIndices(pos, features);
        s.n = uint8_t(n);
        for (int i = 0; i < n; ++i) s.feat[size_t(i)] = uint16_t(features[i]);
        int target = score - (direct ? 0 : base);
        target = std::clamp(target, direct ? -1500 : -800,
                            direct ? 1500 : 800);
        s.target = target / 100.0f;
        s.baseline = base / 100.0f;
        samples.push_back(s);
    }
    std::cerr << "loaded " << samples.size() << " samples, skipped " << skipped
              << "\n";
    return samples;
}

struct Network {
    std::vector<float> w1, b1, w2;
    float b2 = 0.0f;

    Network() {
        w1.assign(NNUE::INPUTS * NNUE::HIDDEN, 0.0f);
        b1.assign(NNUE::HIDDEN, 0.0f);
        w2.assign(NNUE::HIDDEN, 0.0f);
    }

    float forward(const Sample& s, std::array<float, NNUE::HIDDEN>* hidden,
                  std::array<float, NNUE::HIDDEN>* pre = nullptr) const {
        std::array<float, NNUE::HIDDEN> h{};
        for (int j = 0; j < NNUE::HIDDEN; ++j) h[j] = b1[j];
        for (int k = 0; k < s.n; ++k) {
            const float* row = &w1[size_t(s.feat[k]) * NNUE::HIDDEN];
            for (int j = 0; j < NNUE::HIDDEN; ++j) h[j] += row[j];
        }
        if (pre) *pre = h;
        for (int j = 0; j < NNUE::HIDDEN; ++j)
            if (h[j] < 0.0f) h[j] = 0.0f;
        if (hidden) *hidden = h;
        float out = b2;
        for (int j = 0; j < NNUE::HIDDEN; ++j) out += w2[j] * h[j];
        return out;
    }

    float mse(const std::vector<Sample>& data, const std::vector<size_t>& idx) const {
        if (idx.empty()) return 0.0f;
        double sum = 0.0;
        for (size_t i : idx) {
            std::array<float, NNUE::HIDDEN> h{};
            float out = forward(data[i], &h);
            double e = double(out) - data[i].target;
            sum += e * e;
        }
        return float(sum / idx.size());
    }

    float correlation(const std::vector<Sample>& data,
                      const std::vector<size_t>& idx) const {
        if (idx.empty()) return 0.0f;
        double sx = 0, sy = 0, sxx = 0, syy = 0, sxy = 0;
        for (size_t i : idx) {
            std::array<float, NNUE::HIDDEN> h{};
            double x = forward(data[i], &h);
            double y = data[i].target;
            sx += x; sy += y; sxx += x * x; syy += y * y; sxy += x * y;
        }
        double n = double(idx.size());
        double cov = sxy - sx * sy / n;
        double vx = sxx - sx * sx / n;
        double vy = syy - sy * sy / n;
        if (vx <= 1e-12 || vy <= 1e-12) return 0.0f;
        return float(cov / std::sqrt(vx * vy));
    }
};

void writeWeights(const Network& net, const std::string& path, bool direct) {
    std::ofstream out(path);
    out << "// Auto-generated by trainer. Do not edit by hand.\n";
    out << "#include \"engine.hpp\"\n\n";
    out << "namespace chess {\nnamespace NNUE {\n\n";
    out << std::setprecision(8);
    out << "float W1[INPUTS][HIDDEN] = {\n";
    for (int i = 0; i < NNUE::INPUTS; ++i) {
        out << "    {";
        for (int j = 0; j < NNUE::HIDDEN; ++j) {
            if (j) out << ", ";
            out << net.w1[size_t(i) * NNUE::HIDDEN + j] << "f";
        }
        out << "},\n";
    }
    out << "};\n\n";

    out << "float B1[HIDDEN] = {";
    for (int j = 0; j < NNUE::HIDDEN; ++j) {
        if (j) out << ", ";
        out << net.b1[j] << "f";
    }
    out << "};\n\n";

    out << "float W2[HIDDEN] = {";
    for (int j = 0; j < NNUE::HIDDEN; ++j) {
        if (j) out << ", ";
        out << net.w2[j] << "f";
    }
    out << "};\n\n";

    out << "float B2 = " << net.b2 << "f;\n\n";
    out << "bool trained = true;\n";
    out << "bool enabled = false;\n";
    out << "bool direct = " << (direct ? "true" : "false") << ";\n";
    out << "int weight = 25;\n";
    out << "int clip = 80;\n\n";
    out << "void init() {}\n\n";
    out << "} // namespace NNUE\n} // namespace chess\n";
}

int runDatagen(int games, int depth, const std::string& outPath, uint64_t seed) {
    Position pos;
    TranspositionTable tt;
    tt.resize(32);
    Search search(pos, tt);
    search.setSilent(true);

    std::ofstream out(outPath);
    if (!out) {
        std::cerr << "cannot open " << outPath << "\n";
        return 1;
    }

    std::mt19937_64 rng(seed);
    uint64_t positions = 0;
    MoveList list;

    for (int g = 0; g < games; ++g) {
        pos.setStartpos();
        tt.clear();
        search.clearState();

        for (int ply = 0; ply < 220; ++ply) {
            if (pos.isDraw()) break;

            list.clear();
            pos.generateMoves(list);
            std::vector<Move> legal;
            legal.reserve(list.count);
            for (int i = 0; i < list.count; ++i) {
                Move m = list.moves[i];
                if (pos.makeMove(m)) {
                    pos.unmakeMove(m);
                    legal.push_back(m);
                }
            }
            if (legal.empty()) break;

            SearchLimits limits;
            limits.depth = depth;
            limits.infinite = true;
            search.stopFlag.store(false, std::memory_order_relaxed);
            search.run(limits);

            Move best = search.lastBest();
            if (best.isNone()) best = legal[0];
            int score = search.lastScore();

            out << pos.fen() << '|' << score << '\n';
            ++positions;

            Move chosen = best;
            // Diverse openings and occasional deliberate mistakes create a
            // much richer training distribution than pure self-play.
            if (ply < 8 || (rng() % 100) < 8)
                chosen = legal[rng() % legal.size()];
            if (!pos.makeMove(chosen)) break;
        }

        if ((g + 1) % 5 == 0)
            std::cerr << "games " << (g + 1) << "/" << games
                      << " positions " << positions << "\n";
    }

    std::cout << "datagen positions " << positions << " -> " << outPath << "\n";
    return 0;
}

int runStats(const std::string& dataPath, bool direct) {
    auto samples = loadSamples(dataPath, direct);
    if (samples.empty()) {
        std::cerr << "no samples\n";
        return 1;
    }
    double se = 0.0, sy = 0.0, syy = 0.0, sx = 0.0, sxx = 0.0, sxy = 0.0;
    double ymin = 1e9, ymax = -1e9, xmin = 1e9, xmax = -1e9;
    for (const auto& s : samples) {
        double x = s.baseline;
        double y = s.target;
        ymin = std::min(ymin, y);
        ymax = std::max(ymax, y);
        xmin = std::min(xmin, x);
        xmax = std::max(xmax, x);
        double e = x - y;
        se += e * e;
        sx += x; sy += y; sxx += x * x; syy += y * y; sxy += x * y;
    }
    double n = double(samples.size());
    double cov = sxy - sx * sy / n;
    double vx = sxx - sx * sx / n;
    double vy = syy - sy * sy / n;
    double corr = (vx > 1e-12 && vy > 1e-12) ? cov / std::sqrt(vx * vy) : 0.0;
    std::cout << "samples " << samples.size() << " classical_rmse "
              << std::sqrt(se / n) << " target_std " << std::sqrt(vy / n)
              << " corr " << corr << " bias " << (sx - sy) / n
              << " target_range [" << ymin << ", " << ymax << "]"
              << " base_range [" << xmin << ", " << xmax << "]\n";
    return 0;
}

int runTrain(const std::string& dataPath, int epochs, const std::string& outPath,
             bool direct) {
    auto samples = loadSamples(dataPath, direct);
    if (samples.size() < 1000) {
        std::cerr << "not enough samples\n";
        return 1;
    }

    std::mt19937 rng(1234567);
    std::vector<size_t> all(samples.size());
    std::iota(all.begin(), all.end(), 0);
    std::shuffle(all.begin(), all.end(), rng);
    size_t split = size_t(samples.size() * 0.9);
    std::vector<size_t> train(all.begin(), all.begin() + split);
    std::vector<size_t> valid(all.begin() + split, all.end());

    double mean = 0, var = 0;
    for (size_t i : train) mean += samples[i].target;
    mean /= train.size();
    for (size_t i : train) {
        double d = samples[i].target - mean;
        var += d * d;
    }
    var /= train.size();
    std::cerr << "target mean " << mean << " std " << std::sqrt(var) << "\n";

    Network net;
    std::normal_distribution<float> initW(0.0f, 0.03f);
    std::normal_distribution<float> initOut(0.0f, 0.03f);
    for (auto& w : net.w1) w = initW(rng);
    for (auto& w : net.w2) w = initOut(rng);
    net.b2 = float(mean);

    std::vector<float> gW1(NNUE::INPUTS * NNUE::HIDDEN);
    std::vector<float> gB1(NNUE::HIDDEN);
    std::vector<float> gW2(NNUE::HIDDEN);
    float gB2 = 0.0f;

    std::vector<float> mW1(NNUE::INPUTS * NNUE::HIDDEN), vW1(NNUE::INPUTS * NNUE::HIDDEN);
    std::vector<float> mB1(NNUE::HIDDEN), vB1(NNUE::HIDDEN);
    std::vector<float> mW2(NNUE::HIDDEN), vW2(NNUE::HIDDEN);
    float mB2 = 0.0f, vB2 = 0.0f;

    const float beta1 = 0.9f, beta2 = 0.999f, eps = 1e-8f;
    float lr = 0.003f;
    int step = 0;
    int batchSize = 64;
    float bestVal = 1e30f;
    int bestEpoch = 0;
    int patience = 0;
    Network bestNet = net;

    for (int epoch = 1; epoch <= epochs; ++epoch) {
        std::shuffle(train.begin(), train.end(), rng);
        double lossSum = 0.0;
        int batches = 0;

        for (size_t off = 0; off < train.size(); off += batchSize) {
            size_t end = std::min(train.size(), off + batchSize);
            size_t n = end - off;
            std::fill(gW1.begin(), gW1.end(), 0.0f);
            std::fill(gB1.begin(), gB1.end(), 0.0f);
            std::fill(gW2.begin(), gW2.end(), 0.0f);
            gB2 = 0.0f;

            for (size_t t = off; t < end; ++t) {
                const Sample& s = samples[train[t]];
                if (s.n == 0) continue;
                std::array<float, NNUE::HIDDEN> h{};
                std::array<float, NNUE::HIDDEN> pre{};
                float out = net.forward(s, &h, &pre);
                float err = out - s.target;
                lossSum += err * err;
                float dOut = std::clamp(2.0f * err, -5.0f, 5.0f);

                for (int j = 0; j < NNUE::HIDDEN; ++j) {
                    gW2[j] += dOut * h[j];
                    gB2 += dOut;
                    float dh = (pre[j] > 0.0f) ? dOut * net.w2[j] : 0.0f;
                    gB1[j] += dh;
                    if (dh != 0.0f) {
                        for (int k = 0; k < s.n; ++k) {
                            size_t row = size_t(s.feat[k]) * NNUE::HIDDEN + j;
                            gW1[row] += dh;
                        }
                    }
                }
            }

            float inv = 1.0f / float(n);
            ++step;
            float bc1 = 1.0f - std::pow(beta1, step);
            float bc2 = 1.0f - std::pow(beta2, step);

            auto adam = [&](float& w, float& m, float& v, float g) {
                m = beta1 * m + (1 - beta1) * g;
                v = beta2 * v + (1 - beta2) * g * g;
                float mh = m / bc1;
                float vh = v / bc2;
                w -= lr * mh / (std::sqrt(vh) + eps);
            };

            for (int i = 0; i < NNUE::INPUTS * NNUE::HIDDEN; ++i)
                adam(net.w1[i], mW1[i], vW1[i], gW1[i] * inv);
            for (int j = 0; j < NNUE::HIDDEN; ++j) {
                adam(net.b1[j], mB1[j], vB1[j], gB1[j] * inv);
                adam(net.w2[j], mW2[j], vW2[j], gW2[j] * inv);
            }
            adam(net.b2, mB2, vB2, gB2 * inv);
            ++batches;
        }

        float valMse = net.mse(samples, valid);
        float corr = net.correlation(samples, valid);
        float trainMse = float(lossSum / std::max(1, batches * batchSize));
        std::cerr << "epoch " << epoch << " lr " << lr << " train_mse "
                  << trainMse << " val_mse " << valMse << " corr " << corr
                  << "\n";

        if (valMse < bestVal) {
            bestVal = valMse;
            bestEpoch = epoch;
            bestNet = net;
            patience = 0;
        } else {
            ++patience;
        }
        if (patience >= 8) {
            std::cerr << "early stop\n";
            break;
        }
        lr *= 0.97f;
    }

    std::cerr << "best epoch " << bestEpoch << " val_mse " << bestVal
              << " corr " << bestNet.correlation(samples, valid) << "\n";
    writeWeights(bestNet, outPath, direct);
    std::cout << "weights written to " << outPath << "\n";
    return 0;
}

} // namespace

int main(int argc, char** argv) {
    std::ios::sync_with_stdio(false);
    chess::initAll();

    if (argc < 2) {
        std::cerr
            << "usage:\n"
            << "  trainer datagen <games> <depth> <out.txt> [seed]\n"
            << "  trainer train <data.txt> <epochs> <out_nnue.cpp> [direct]\n"
            << "  trainer stats <data.txt> [direct]\n";
        return 1;
    }

    std::string mode = argv[1];
    if (mode == "stats") {
        if (argc < 3) return 1;
        bool direct = argc >= 4 && std::string(argv[3]) == "direct";
        return runStats(argv[2], direct);
    }
    if (argc < 5) {
        std::cerr << "missing arguments\n";
        return 1;
    }
    if (mode == "datagen") {
        int games = std::stoi(argv[2]);
        int depth = std::stoi(argv[3]);
        std::string out = argv[4];
        uint64_t seed = 12345;
        if (argc >= 6) seed = std::stoull(argv[5]);
        return runDatagen(games, depth, out, seed);
    }
    if (mode == "train") {
        std::string data = argv[2];
        int epochs = std::stoi(argv[3]);
        std::string out = argv[4];
        bool direct = argc >= 6 && std::string(argv[5]) == "direct";
        return runTrain(data, epochs, out, direct);
    }

    std::cerr << "unknown mode\n";
    return 1;
}
